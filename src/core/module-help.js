const HELP_MODAL_CLOSE_MS = 200;

function prefersReducedMotionHelp() {
  return typeof window !== 'undefined' && window.matchMedia?.('(prefers-reduced-motion: reduce)').matches;
}

function closeModal(modal) {
  if (!(modal instanceof HTMLElement) || modal.classList.contains('is-closing')) return;
  if (prefersReducedMotionHelp()) {
    modal.remove();
    return;
  }
  modal.classList.add('is-closing');
  window.setTimeout(() => modal.remove(), HELP_MODAL_CLOSE_MS);
}

export function showModuleHelp(moduleId) {
  const help = MODULES_HELP[moduleId];
  if (!help) return;

  document.querySelector('.module-help-overlay')?.remove();

  const modal = document.createElement('div');
  modal.className = 'module-help-overlay';
  modal.innerHTML = `
    <div class="module-help-modal">
      <div class="module-help-header">
        <h2 class="module-help-title">${help.title}</h2>
        <button type="button" class="module-help-close" data-help-close aria-label="Fermer">✕</button>
      </div>
      <div class="module-help-body">
        <div class="module-help-section">
          <span class="module-help-label">Le défi</span>
          <p>${help.problem}</p>
        </div>
        <div class="module-help-section">
          <span class="module-help-label">Comment ça aide</span>
          <p>${help.why}</p>
        </div>
        <div class="module-help-tip">💡 ${help.tip}</div>
      </div>
      <button type="button" class="btn btn-primary module-help-btn" data-help-close>
        C'est parti !
      </button>
    </div>
  `;

  modal.addEventListener('click', (e) => {
    const target = e.target;
    if (!(target instanceof HTMLElement)) return;
    if (target.dataset.helpClose !== undefined || target === modal) {
      closeModal(modal);
    }
  });

  document.body.appendChild(modal);
}
